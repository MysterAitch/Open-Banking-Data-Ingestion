#: Safe in full: types, currencies, timestamps - values that describe the
#: record rather than identify a person or an account.
SHOW = "show"
#: A closed set of known values - DEBIT/CREDIT, a status, a category. Safe
#: for a different reason from SHOW: the value set is public knowledge and
#: says only which bucket a record fell into. Declaring it also makes
#: misclassification DETECTABLE - a field claimed categorical whose
#: observed cardinality is large is either wrong or the provider changed
#: something, and either way somebody should look.
CATEGORICAL = "categorical"
#: An identifier that CAN be rotated: one we mint ourselves (regenerated by
#: a rebuild) or one the provider mints (opaque, meaningful only inside
#: their system). Shown, because the cost of exposure is proportional to
#: the cost of rotation - and because these already appear throughout the
#: UI in bind boxes and feeder lines, so withholding them HERE would be
#: incoherent as well as useless for debugging.
OPAQUE_ID = "opaque-id"
#: Ranges and formats only. Monetary values: the span and the precision are
#: what a person is reading the shape page FOR, but the individual amounts
#: are their spending.
RANGE_ONLY = "range-only"
#: Structure only - presence, types, length, format. Never a value, and
#: never a common prefix: for a single-account payload the prefix IS the
#: account number.
SHAPE_ONLY = "shape-only"
#: A real-world identifier that CANNOT be rotated: a sort code and account
#: number outlive any breach, and changing one means closing the account.
#: The opposite end of the axis from OPAQUE_ID, and the reason the two are
#: treated differently despite both being "identifiers".
PERMANENT_ID = "permanent-id"
#: A person: names, addresses, contact details.
PERSONAL = "personal"
#: Free text a human wrote. Withheld not because of what it usually says
#: but because nothing constrains what it CAN say - a reference field is
#: exactly where somebody types what they would not choose to publish.
NARRATIVE = "narrative"
#: Arrived already redacted. Shown as sent, and labelled as the provider's
#: choice rather than ours.
PROVIDER_PARTIAL = "provider-partial"
#: Nobody has classified this yet, so it is withheld and says so loudly.
UNCLASSIFIED = "unclassified"

#: Credentials. These belong in the credential store and must never reach
#: a landed payload; if one appears in evidence that is an incident, not a
#: display question, so it is withheld AND said loudly.
CREDENTIAL = "credential"


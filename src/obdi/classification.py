    (r"^running_balance\.amount$", RANGE_ONLY),
    (r"^(sourceAmount|totalFeeAmount)\..*$", RANGE_ONLY),
    # --- descriptive: safe in full ---
    (r"^(currency|country)$", SHOW),
    (r"^(account_type|accountType|card_type|card_network)$", CATEGORICAL),
    (r"^(transaction_type|transaction_category|status|direction|source)$", CATEGORICAL),
